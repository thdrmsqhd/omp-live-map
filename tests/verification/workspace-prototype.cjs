test("18 contracts, schema and cycle validation, isolated evaluation, immutable run snapshot", () => {
  const { families, types } = globalThis.WORKSPACE_CATALOG;
  assert.deepEqual(families.map(f => types.filter(t => t.family === f.id).length), [4, 4, 3, 2, 3, 2]);
  assert.equal(new Set(types.map(t => t.outputSchema)).size, 18);
  for (const t of types) for (const k of ["input", "output", "criteria", "handoff", "stop"]) assert.ok(t[k].trim(), `${t.id}.${k}`);
  const graph = M.clone(M.defaultGraph);
  assert.deepEqual(M.validate(graph).order.map(n => n.id), ["find", "reply", "eval"]);
  const run = M.newRun(graph);
  graph.nodes[0].value = "changed";
  assert.notEqual(run.instruction, graph.nodes[0].value);
  graph.edges.push({ from: "eval", to: "find", schema: "evaluation_report" });
  assert.match(M.validate(graph).error, /외부 평가/);
  graph.edges.pop(); graph.edges[0].schema = "wrong";
  assert.match(M.validate(graph).error, /스키마 불일치/);
  graph.edges[0].schema = "evidence_list";
  graph.nodes.find(n => n.id === "find").inputSchema = "cited_answer";
  graph.edges.push({ from: "reply", to: "find", schema: "cited_answer" });
  assert.match(M.validate(graph).error, /순환/);
  graph.edges = [];
  assert.ok(!M.validate(graph).order.find(n => n.id === "eval"));
  for (const id of ["browser", "system", "deploy"]) assert.equal(M.gate({ type: id }).kind, "HITL");
});

